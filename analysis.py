
import os

import matplotlib
matplotlib.use("Agg")

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from database import get_connection


def analyze_waste():

    # Create the static folder for chart images
    folder_path = os.path.join(
        os.path.dirname(__file__), "static"
    )
    os.makedirs(folder_path, exist_ok=True)

    # Read waste records from MySQL
    connection = get_connection()
    cursor = connection.cursor()

    query = """
    SELECT record_date, location, waste_category,
           waste_type, quantity_kg
    FROM waste_records
    ORDER BY record_date
    """

    cursor.execute(query)
    records = cursor.fetchall()

    cursor.close()
    connection.close()

    columns = [
        "record_date",
        "location",
        "waste_category",
        "waste_type",
        "quantity_kg"
    ]

    # Store database records in a Pandas DataFrame
    df = pd.DataFrame(records, columns=columns)

    category_chart = "category_chart.png"
    monthly_chart = "monthly_chart.png"

    # Display placeholder charts if there are no records
    if len(df) == 0:

        plt.figure(figsize=(7, 4))
        plt.text(
            0.5, 0.5, "No waste records available",
            ha="center", va="center"
        )
        plt.axis("off")
        plt.savefig(
            os.path.join(folder_path, category_chart)
        )
        plt.close()

        plt.figure(figsize=(8, 4))
        plt.text(
            0.5, 0.5, "No waste records available",
            ha="center", va="center"
        )
        plt.axis("off")
        plt.savefig(
            os.path.join(folder_path, monthly_chart)
        )
        plt.close()

        return {
            "average_waste": 0,
            "category_chart": category_chart,
            "monthly_chart": monthly_chart
        }

    # Convert dates into Pandas datetime format
    df["record_date"] = pd.to_datetime(df["record_date"])

    # Calculate average waste using NumPy
    average_waste = np.mean(df["quantity_kg"])

    # Group total waste by category using Pandas
    category_data = df.groupby(
        "waste_category"
    )["quantity_kg"].sum()

    # Create the category bar chart using Matplotlib
    plt.figure(figsize=(7, 4))
    category_data.plot(kind="bar")

    plt.title("Waste Generated by Category")
    plt.xlabel("Waste Category")
    plt.ylabel("Waste Recorded (kg)")
    plt.tight_layout()

    plt.savefig(
        os.path.join(folder_path, category_chart)
    )
    plt.close()

    # Extract month from each record date
    
    # Extract the month from each record date
    df["month"] = df["record_date"].dt.to_period("M").astype(str)

    # Group waste by month and waste type using Pandas
    monthly_data = df.groupby(
        ["month", "waste_type"]
    )["quantity_kg"].sum().unstack(fill_value=0)

    # Create the monthly line chart
    fig, ax = plt.subplots(figsize=(9, 5))

    monthly_data.plot(
        kind="line",
        marker="o",
        ax=ax
    )

    ax.set_title("Monthly Waste Comparison by Type")
    ax.set_xlabel("Month")
    ax.set_ylabel("Waste Recorded (kg)")
    ax.tick_params(axis="x", labelrotation=45)
    ax.legend(title="Waste Type")

    fig.tight_layout()

    # Save the chart image
    chart_path = os.path.join(
        folder_path, monthly_chart
    )

    fig.savefig(chart_path, format="png")
    plt.close(fig)

    return {
        "average_waste": float(np.round(average_waste, 2)),
        "category_chart": category_chart,
        "monthly_chart": monthly_chart
    }
